RESULT_COLS = [
    "Incident", "Severity", "Assignment status", "Ambulance", "Hospital",
    "Hospital occupancy (%)", "Dispatch (min)", "Transport (min)",
    "Hospital delay (min)", "Total time (min)", "Uncertainty buffer (min)",
    "Risk score", "Decision score",
]


def _strategy_block(scenario: dict, strategy: str, label: str) -> pd.DataFrame:
    """Render one strategy's assignment table, explanations and map."""
    result = dispatch(scenario, strategy=strategy)
    served = result[result["Assignment status"] == "Served"]
    unserved = result[result["Assignment status"] == "Unserved"]

    if len(unserved):
        st.warning(
            f"**{len(unserved)} incident(s) have no feasible assignment** "
            f"({', '.join(unserved['Incident'])}) - all ambulances are already "
            "dispatched. Reported explicitly; ambulances are never reused.",
            icon="⚠️")

    shown = result[[c for c in RESULT_COLS if c in result.columns]].copy()
    shown["Explanation"] = result.apply(explain_row, axis=1)
    st.dataframe(shown, hide_index=True, use_container_width=True,
                 column_config={"Explanation": st.column_config.TextColumn(
                     "Explanation (simulated rationale)", width="large")})

    st.plotly_chart(build_map(scenario, result, label),
                    use_container_width=True)

    if len(served):
        times = served.melt(
            id_vars=["Incident"],
            value_vars=["Dispatch (min)", "Transport (min)", "Hospital delay (min)"],
            var_name="Phase", value_name="Minutes")
        fig = px.bar(times, x="Incident", y="Minutes", color="Phase",
                     barmode="stack",
                     color_discrete_sequence=[BLUE, "#5DADE2", AMBER],
                     title=f"{label}: estimated time breakdown per incident "
                           "(simulated minutes)")
        fig.update_layout(height=340, margin=dict(l=0, r=0, t=40, b=0))
        st.plotly_chart(fig, use_container_width=True)
    else:
        st.info("No served assignments to chart for this strategy.")
    return result


def page_dispatch() -> None:
    st.title("\U0001F6A8 Emergency Dispatch")
    st.markdown('<div class="rx-sub">Both strategies run on the <b>same '
                "scenario</b> with identical constraints: one dispatch per "
                "ambulance, feasibility checked, unserved incidents reported "
                "explicitly.</div>", unsafe_allow_html=True)

    scenario = current_scenario()
    baseline = dispatch(scenario, strategy="baseline")
    resqx = dispatch(scenario, strategy="resqx")

    # ---- side-by-side summary -------------------------------------------
    st.subheader("Strategy summary (same input scenario)")
    rows = []
    for label, res in (("Baseline (nearest available)", baseline),
                       ("RESQ-X (risk-aware)", resqx)):
        m = summary_of(res, scenario["ambulances"])
        rows.append({
            "Strategy": label,
            "Served / Unserved": f"{m['n_served']} / {m['n_unserved']}",
            "Mean dispatch (min)": round(m["mean_dispatch"], 2),
            "Mean end-to-end (min)": round(m["mean_end_to_end"], 2),
            "Mean hospital delay (min)": round(m["mean_hospital_delay"], 2),
            "Mean risk score": round(m["mean_risk_score"], 1),
            "Mean decision score": round(m["mean_decision_score"], 1),
        })
    st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)
    st.caption("All values are simulated estimates from the executed run.")

    tab_b, tab_x = st.tabs(["Baseline strategy", "RESQ-X risk-aware strategy"])
    with tab_b:
        st.markdown(
            "**Baseline:** nearest available ambulance (by simulated dispatch "
            "time), then nearest hospital. No ambulance is dispatched twice.")
        _strategy_block(scenario, "baseline", "Baseline")
    with tab_x:
        st.markdown(
            "**RESQ-X:** generates every feasible ambulance x hospital "
            "candidate, estimates dispatch / transport / hospital delay, adds "
            "an uncertainty buffer and a weighted congestion-risk penalty, then "
            "picks the lowest explainable decision score per incident.")
        _strategy_block(scenario, "resqx", "RESQ-X")

