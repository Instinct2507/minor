def explain_row(row) -> str:
    """Human-readable rationale for one assignment row."""
    if row.get("Assignment status") != "Served":
        return ("No feasible assignment: every ambulance was already dispatched "
                "to another incident. Reported as Unserved - never reused.")
    buffer = row.get("Uncertainty buffer (min)", 0.0) or 0.0
    return (
        f"{row['Ambulance']} reaches {row['Incident']} in an estimated "
        f"{row['Dispatch (min)']:.1f} min (simulated). {row['Hospital']} at "
        f"{row['Hospital occupancy (%)']:.0f}% occupancy adds ~"
        f"{row['Hospital delay (min)']:.1f} min wait. Risk score "
        f"{row['Risk score']:.0f}/100; uncertainty buffer +{buffer:.1f} min. "
        f"Decision score {row['Decision score']:.1f} (lower is better)."
    )

