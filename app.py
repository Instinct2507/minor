# --------------------------------------------------------------- map builder
def build_map(scenario: dict, result: pd.DataFrame, strategy_label: str) -> go.Figure:
    """Synthetic city grid with distinct markers and assignment routes."""
    amb = scenario["ambulances"]
    hosp = scenario["hospitals"]
    inc = scenario["incidents"]
    served = result[result["Assignment status"] == "Served"] if len(result) else result

    fig = go.Figure()

    # assignment routes: ambulance -> incident -> hospital
    xs: list = []
    ys: list = []
    for _, row in served.iterrows():
        a = amb[amb["Ambulance"] == row["Ambulance"]]
        h = hosp[hosp["Hospital"] == row["Hospital"]]
        i = inc[inc["Incident"] == row["Incident"]]
        if a.empty or h.empty or i.empty:
            continue
        xs += [a.iloc[0]["x"], i.iloc[0]["x"], h.iloc[0]["x"], None]
        ys += [a.iloc[0]["y"], i.iloc[0]["y"], h.iloc[0]["y"], None]
    if xs:
        fig.add_trace(go.Scatter(
            x=xs, y=ys, mode="lines",
            line=dict(color=AMBER, width=2, dash="dot"),
            name=f"Routes ({strategy_label})", hoverinfo="skip"))

    # hospitals (squares, colour = occupancy)
    fig.add_trace(go.Scatter(
        x=hosp["x"], y=hosp["y"], mode="markers+text",
        marker=dict(symbol="square", size=17,
                    color=hosp["occupancy"], colorscale="RdYlGn_r",
                    line=dict(color=NAVY, width=1)),
        text=hosp["Hospital"], textposition="top center",
        textfont=dict(size=9, color=NAVY), name="Hospitals",
        customdata=np.stack([hosp["Hospital"], hosp["occupancy"],
                             hosp["base_delay"]], axis=-1),
        hovertemplate=("<b>%{customdata[0]}</b> (hospital)<br>"
                       "Occupancy: %{customdata[1]:.0f}%<br>"
                       "Base delay: ~%{customdata[2]:.0f} min<br>"
                       "<i>synthetic</i><extra></extra>")))

    # ambulances: available vs busy
    for status, colour, sym in (("Available", BLUE, "circle"),
                                ("Busy", GREY, "x")):
        sub = amb[amb["status"] == status]
        if sub.empty:
            continue
        fig.add_trace(go.Scatter(
            x=sub["x"], y=sub["y"], mode="markers",
            marker=dict(symbol=sym, size=14, color=colour,
                        line=dict(color="white", width=1)),
            name=f"Ambulances - {status}",
            customdata=np.stack([sub["Ambulance"], sub["type"]], axis=-1),
            hovertemplate=("<b>%{customdata[0]}</b> (%{customdata[1]})<br>"
                           f"Status: {status}<br>"
                           "<i>synthetic position</i><extra></extra>")))

    # incidents (diamonds)
    served_ids = set(served["Incident"]) if len(served) else set()
    inc_col = inc["severity"].map(
        {"Critical": "#8E1B1B", "High": RED, "Medium": "#E67E22", "Low": "#F1C40F"})
    fig.add_trace(go.Scatter(
        x=inc["x"], y=inc["y"], mode="markers",
        marker=dict(symbol="diamond", size=13, color=inc_col,
                    line=dict(color="white", width=1)),
        name="Incidents",
        customdata=np.stack([inc["Incident"], inc["severity"], inc["urgency"]],
                            axis=-1),
        hovertemplate=("<b>%{customdata[0]}</b> (incident)<br>"
                       "Severity: %{customdata[1]}<br>"
                       "Urgency: %{customdata[2]:.1f}<br>"
                       "<i>synthetic</i><extra></extra>")))

    fig.update_layout(
        height=540,
        xaxis=dict(range=[-0.6, 10.6], dtick=1, showgrid=True,
                   gridcolor="#DDE5F0", zeroline=False),
        yaxis=dict(range=[-0.6, 10.6], dtick=1, showgrid=True,
                   gridcolor="#DDE5F0", zeroline=False, scaleanchor="x"),
        plot_bgcolor="#FFFFFF",
        margin=dict(l=10, r=10, t=40, b=10),
        legend=dict(orientation="h", yanchor="bottom", y=-0.18,
                    xanchor="center", x=0.5),
        title=dict(text="Synthetic 10x10 city grid (NOT a real map)",
                   font=dict(size=13, color=GREY), x=0.01),
        font=dict(color=NAVY))
    return fig

